"""
Excel export service for the KTU Mark Processing System.

Creates a professional Excel workbook containing:

    Registration Number
    Internal Mark
    <COURSE_CODE> Grade

Example:

    Registration Number | Internal Mark | CST309 Grade
    --------------------------------------------------
    CEC23CS003          | 47            | A
    CEC23CS004          | 47            | A
    CEC23CS005          | 46            | B+
    CEC23CS006          | 37            | F

A second worksheet called "Processing Summary" contains
matching statistics and mismatch information.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import List, Dict, Any

from openpyxl import Workbook
from openpyxl.styles import (
    Font,
    Alignment,
    PatternFill,
    Border,
    Side,
)
from openpyxl.worksheet.table import Table, TableStyleInfo
from openpyxl.utils import get_column_letter


class ExcelExportError(ValueError):
    """
    Raised when Excel export fails.
    """



# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _normalize_course_code(
    course_code: str,
) -> str:
    """
    Normalize course code.

    Examples:

        "cst309" -> "CST309"
        " CST309 " -> "CST309"
    """

    if course_code is None:
        raise ExcelExportError(
            "Course code is required for Excel export."
        )

    code = str(
        course_code
    ).strip().upper()

    code = re.sub(
        r"\s+",
        "",
        code,
    )

    if not code:

        raise ExcelExportError(
            "Course code cannot be empty."
        )

    return code


def _validate_results(
    results: List[dict],
) -> List[dict]:
    """
    Validate the final results list before writing Excel.
    """

    if not isinstance(results, list):
        raise ExcelExportError(
            "Results must be provided as a list."
        )

    if not results:
        raise ExcelExportError(
            "There are no results to export."
        )

    cleaned_results = []

    seen_reg_numbers = set()

    for index, row in enumerate(results, start=1):

        if not isinstance(row, dict):

            raise ExcelExportError(
                f"Invalid result record at row {index}."
            )

        reg_no = str(
            row.get(
                "reg_no",
                ""
            )
        ).strip().upper()

        if not reg_no:

            raise ExcelExportError(
                f"Registration number is missing "
                f"at result row {index}."
            )

        if reg_no in seen_reg_numbers:

            raise ExcelExportError(
                f"Duplicate registration number "
                f"found in results: {reg_no}"
            )

        seen_reg_numbers.add(
            reg_no
        )

        internal_mark = row.get(
            "internal_mark"
        )

        if internal_mark is None:

            raise ExcelExportError(
                f"Internal mark is missing for {reg_no}."
            )

        grade = row.get(
            "grade",
            "Not Found",
        )

        if grade is None:
            grade = "Not Found"

        grade = str(
            grade
        ).strip()

        cleaned_results.append(
            {
                "reg_no": reg_no,
                "internal_mark": internal_mark,
                "grade": grade,
            }
        )

    return cleaned_results


def _safe_filename(
    filename: str,
) -> str:
    """
    Convert a user/course-derived filename into a safe filename.
    """

    filename = re.sub(
        r"[^A-Za-z0-9_.-]+",
        "_",
        filename,
    )

    return filename.strip(
        "._"
    ) or "marks"


# ---------------------------------------------------------------------------
# Main Excel generator
# ---------------------------------------------------------------------------

def generate_excel(
    results: List[dict],
    course_code: str,
    output_path: str | Path,
    *,
    summary: Dict[str, Any] | None = None,
    branch: str = "COMPUTER SCIENCE & ENGINEERING",
    semester: str = "",
) -> Path:
    """
    Generate a formatted Excel workbook.

    Parameters
    ----------
    results:
        Final merged student records.

    course_code:
        Manually selected course code such as CST309.

    output_path:
        Where the .xlsx file should be created.

    summary:
        Optional matching summary generated by matcher.py.

    branch:
        Branch displayed in workbook.

    semester:
        Semester displayed in workbook.

    Returns
    -------
    pathlib.Path
        Path to generated Excel file.
    """

    course_code = _normalize_course_code(
        course_code
    )

    results = _validate_results(
        results
    )

    output = Path(
        output_path
    )

    # Make sure parent folder exists.
    output.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    # -----------------------------------------------------------------------
    # Create workbook
    # -----------------------------------------------------------------------

    workbook = Workbook()

    worksheet = workbook.active

    worksheet.title = "Marks"

    # -----------------------------------------------------------------------
    # Colors/styles
    # -----------------------------------------------------------------------

    title_fill = PatternFill(
        fill_type="solid",
        fgColor="1F2937",
    )

    header_fill = PatternFill(
        fill_type="solid",
        fgColor="374151",
    )

    information_fill = PatternFill(
        fill_type="solid",
        fgColor="F3F4F6",
    )

    warning_fill = PatternFill(
        fill_type="solid",
        fgColor="FEF3C7",
    )

    title_font = Font(
        bold=True,
        size=16,
        color="FFFFFF",
    )

    header_font = Font(
        bold=True,
        color="FFFFFF",
        size=11,
    )

    normal_font = Font(
        size=11,
    )

    bold_font = Font(
        bold=True,
        size=11,
    )

    white_font = Font(
        color="FFFFFF",
        bold=True,
    )

    thin_side = Side(
        style="thin",
        color="D1D5DB",
    )

    medium_side = Side(
        style="medium",
        color="9CA3AF",
    )

    thin_border = Border(
        left=thin_side,
        right=thin_side,
        top=thin_side,
        bottom=thin_side,
    )

    # -----------------------------------------------------------------------
    # Title
    # -----------------------------------------------------------------------

    worksheet.merge_cells(
        "A1:C1"
    )

    worksheet["A1"] = (
        "KTU MARK PROCESSING SYSTEM"
    )

    worksheet["A1"].fill = title_fill
    worksheet["A1"].font = title_font
    worksheet["A1"].alignment = Alignment(
        horizontal="center",
        vertical="center",
    )

    worksheet.row_dimensions[1].height = 30

    # -----------------------------------------------------------------------
    # Information
    # -----------------------------------------------------------------------

    worksheet["A2"] = "Course Code"
    worksheet["B2"] = course_code

    worksheet["A3"] = "Branch"
    worksheet["B3"] = branch

    worksheet["A4"] = "Semester"
    worksheet["B4"] = semester or "Not specified"

    worksheet["A5"] = "Total Students"
    worksheet["B5"] = len(results)

    for row_number in range(
        2,
        6,
    ):

        worksheet[f"A{row_number}"].font = bold_font
        worksheet[f"A{row_number}"].fill = information_fill

        worksheet[f"A{row_number}"].border = thin_border
        worksheet[f"B{row_number}"].border = thin_border

        worksheet[f"A{row_number}"].alignment = Alignment(
            vertical="center"
        )

        worksheet[f"B{row_number}"].alignment = Alignment(
            vertical="center"
        )

    # -----------------------------------------------------------------------
    # Header row
    # -----------------------------------------------------------------------

    header_row = 7

    headers = [
        "Registration Number",
        "Internal Mark",
        f"{course_code} Grade",
    ]

    for column_number, header in enumerate(
        headers,
        start=1,
    ):

        cell = worksheet.cell(
            row=header_row,
            column=column_number,
        )

        cell.value = header

        cell.fill = header_fill
        cell.font = header_font

        cell.alignment = Alignment(
            horizontal="center",
            vertical="center",
        )

        cell.border = Border(
            left=medium_side,
            right=medium_side,
            top=medium_side,
            bottom=medium_side,
        )

    worksheet.row_dimensions[
        header_row
    ].height = 30

    # -----------------------------------------------------------------------
    # Data
    # -----------------------------------------------------------------------

    first_data_row = header_row + 1

    for index, student in enumerate(
        results,
        start=first_data_row,
    ):

        worksheet.cell(
            row=index,
            column=1,
            value=student["reg_no"],
        )

        worksheet.cell(
            row=index,
            column=2,
            value=student["internal_mark"],
        )

        worksheet.cell(
            row=index,
            column=3,
            value=student["grade"],
        )

        for column_number in range(
            1,
            4,
        ):

            cell = worksheet.cell(
                row=index,
                column=column_number,
            )

            cell.font = normal_font

            cell.alignment = Alignment(
                horizontal="center",
                vertical="center",
            )

            cell.border = thin_border

        # Highlight missing grades.
        if student["grade"] == "Not Found":

            worksheet.cell(
                row=index,
                column=3,
            ).fill = warning_fill

    last_data_row = (
        first_data_row
        + len(results)
        - 1
    )

    # -----------------------------------------------------------------------
    # Excel table
    # -----------------------------------------------------------------------

    table_reference = (
        f"A{header_row}:C{last_data_row}"
    )

    table = Table(
        displayName="MarksTable",
        ref=table_reference,
    )

    table_style = TableStyleInfo(
        name="TableStyleMedium2",
        showFirstColumn=False,
        showLastColumn=False,
        showRowStripes=True,
        showColumnStripes=False,
    )

    table.tableStyleInfo = table_style

    worksheet.add_table(
        table
    )

    # -----------------------------------------------------------------------
    # Column sizes
    # -----------------------------------------------------------------------

    column_widths = {
        "A": 25,
        "B": 18,
        "C": 18,
    }

    for column, width in column_widths.items():

        worksheet.column_dimensions[
            column
        ].width = width

    # -----------------------------------------------------------------------
    # Freeze panes
    # -----------------------------------------------------------------------

    worksheet.freeze_panes = (
        f"A{first_data_row}"
    )

    # -----------------------------------------------------------------------
    # Filter
    # -----------------------------------------------------------------------

    worksheet.auto_filter.ref = (
        table_reference
    )

    # -----------------------------------------------------------------------
    # Page settings
    # -----------------------------------------------------------------------

    worksheet.sheet_view.showGridLines = False

    worksheet.page_setup.orientation = (
        "landscape"
    )

    worksheet.page_setup.fitToWidth = 1
    worksheet.page_setup.fitToHeight = 0

    worksheet.sheet_properties.pageSetUpPr.fitToPage = True

    # -----------------------------------------------------------------------
    # Processing Summary worksheet
    # -----------------------------------------------------------------------

    summary_sheet = workbook.create_sheet(
        "Processing Summary"
    )

    summary_sheet.sheet_view.showGridLines = False

    summary_sheet.merge_cells(
        "A1:B1"
    )

    summary_sheet["A1"] = (
        "PROCESSING SUMMARY"
    )

    summary_sheet["A1"].fill = title_fill
    summary_sheet["A1"].font = title_font

    summary_sheet["A1"].alignment = Alignment(
        horizontal="center",
        vertical="center",
    )

    summary_sheet.row_dimensions[
        1
    ].height = 30

    # Create summary automatically if none was supplied.
    if summary is None:

        matched_count = sum(
            1
            for student in results
            if student["grade"] != "Not Found"
        )

        missing_count = sum(
            1
            for student in results
            if student["grade"] == "Not Found"
        )

        missing_reg_numbers = [
            student["reg_no"]
            for student in results
            if student["grade"] == "Not Found"
        ]

        summary = {
            "total_internal_students": len(
                results
            ),
            "total_result_students": "",
            "matched_students": matched_count,
            "missing_grades": missing_count,
            "result_only_students": "",
            "missing_grade_reg_numbers":
                missing_reg_numbers,
            "result_only_reg_numbers": [],
        }

    summary_rows = [
        (
            "Course Code",
            course_code,
        ),
        (
            "Branch",
            branch,
        ),
        (
            "Semester",
            semester or "Not specified",
        ),
        (
            "Students in Internal PDF",
            summary.get(
                "total_internal_students",
                "",
            ),
        ),
        (
            "Students in Result PDF",
            summary.get(
                "total_result_students",
                "",
            ),
        ),
        (
            "Matched Students",
            summary.get(
                "matched_students",
                "",
            ),
        ),
        (
            "Missing Grades",
            summary.get(
                "missing_grades",
                "",
            ),
        ),
        (
            "Result-only Students",
            summary.get(
                "result_only_students",
                "",
            ),
        ),
    ]

    start_row = 3

    for index, (
        label,
        value,
    ) in enumerate(
        summary_rows,
        start=start_row,
    ):

        summary_sheet.cell(
            row=index,
            column=1,
            value=label,
        )

        summary_sheet.cell(
            row=index,
            column=2,
            value=value,
        )

        summary_sheet.cell(
            row=index,
            column=1,
        ).font = bold_font

        summary_sheet.cell(
            row=index,
            column=1,
        ).fill = information_fill

        summary_sheet.cell(
            row=index,
            column=1,
        ).border = thin_border

        summary_sheet.cell(
            row=index,
            column=2,
        ).border = thin_border

        summary_sheet.cell(
            row=index,
            column=1,
        ).alignment = Alignment(
            vertical="center"
        )

        summary_sheet.cell(
            row=index,
            column=2,
        ).alignment = Alignment(
            vertical="center",
            wrap_text=True,
        )

    # -----------------------------------------------------------------------
    # Missing grade section
    # -----------------------------------------------------------------------

    missing_start = (
        start_row
        + len(summary_rows)
        + 2
    )

    summary_sheet.merge_cells(
        start_row=missing_start,
        start_column=1,
        end_row=missing_start,
        end_column=2,
    )

    summary_sheet.cell(
        row=missing_start,
        column=1,
        value="STUDENTS WITHOUT MATCHED GRADE",
    )

    summary_sheet.cell(
        row=missing_start,
        column=1,
    ).fill = warning_fill

    summary_sheet.cell(
        row=missing_start,
        column=1,
    ).font = bold_font

    missing_reg_numbers = summary.get(
        "missing_grade_reg_numbers",
        [],
    )

    missing_row = (
        missing_start + 1
    )

    if missing_reg_numbers:

        for reg_no in missing_reg_numbers:

            summary_sheet.cell(
                row=missing_row,
                column=1,
                value=reg_no,
            )

            summary_sheet.cell(
                row=missing_row,
                column=2,
                value="Grade not found",
            )

            summary_sheet.cell(
                row=missing_row,
                column=1,
            ).border = thin_border

            summary_sheet.cell(
                row=missing_row,
                column=2,
            ).border = thin_border

            missing_row += 1

    else:

        summary_sheet.cell(
            row=missing_row,
            column=1,
            value="None",
        )

        summary_sheet.cell(
            row=missing_row,
            column=2,
            value="All internal-mark students matched.",
        )

        summary_sheet.cell(
            row=missing_row,
            column=1,
        ).border = thin_border

        summary_sheet.cell(
            row=missing_row,
            column=2,
        ).border = thin_border

    # -----------------------------------------------------------------------
    # Result-only students
    # -----------------------------------------------------------------------

    result_only_start = (
        missing_row + 2
    )

    summary_sheet.merge_cells(
        start_row=result_only_start,
        start_column=1,
        end_row=result_only_start,
        end_column=2,
    )

    summary_sheet.cell(
        row=result_only_start,
        column=1,
        value="RESULT-ONLY REGISTRATION NUMBERS",
    )

    summary_sheet.cell(
        row=result_only_start,
        column=1,
    ).fill = information_fill

    summary_sheet.cell(
        row=result_only_start,
        column=1,
    ).font = bold_font

    result_only_reg_numbers = summary.get(
        "result_only_reg_numbers",
        [],
    )

    result_only_row = (
        result_only_start + 1
    )

    if result_only_reg_numbers:

        for reg_no in result_only_reg_numbers:

            summary_sheet.cell(
                row=result_only_row,
                column=1,
                value=reg_no,
            )

            summary_sheet.cell(
                row=result_only_row,
                column=2,
                value="Not present in internal PDF",
            )

            summary_sheet.cell(
                row=result_only_row,
                column=1,
            ).border = thin_border

            summary_sheet.cell(
                row=result_only_row,
                column=2,
            ).border = thin_border

            result_only_row += 1

    else:

        summary_sheet.cell(
            row=result_only_row,
            column=1,
            value="None",
        )

        summary_sheet.cell(
            row=result_only_row,
            column=2,
            value="No extra result records.",
        )

        summary_sheet.cell(
            row=result_only_row,
            column=1,
        ).border = thin_border

        summary_sheet.cell(
            row=result_only_row,
            column=2,
        ).border = thin_border

    # -----------------------------------------------------------------------
    # Summary column widths
    # -----------------------------------------------------------------------

    summary_sheet.column_dimensions[
        "A"
    ].width = 35

    summary_sheet.column_dimensions[
        "B"
    ].width = 45

    # -----------------------------------------------------------------------
    # Save
    # -----------------------------------------------------------------------

    try:

        workbook.save(
            output
        )

    except PermissionError as exc:

        raise ExcelExportError(
            "Could not save the Excel file. "
            "Make sure the file is not already open in Excel."
        ) from exc

    except Exception as exc:

        raise ExcelExportError(
            f"Could not create Excel file: {exc}"
        ) from exc

    return output


# ---------------------------------------------------------------------------
# Suggested filename helper
# ---------------------------------------------------------------------------

def make_excel_filename(
    course_code: str,
) -> str:
    """
    Create a clean filename.

    Example:

        CST309
        ->
        CST309_Marks.xlsx
    """

    course_code = _normalize_course_code(
        course_code
    )

    filename = (
        f"{course_code}_Marks.xlsx"
    )

    return _safe_filename(
        filename
    )


